import { describe, expect, it } from "vitest";
import { kitStamp, tokensScript } from "../../src/kits/output.ts";
import { kitCss } from "../../src/kits/runtime.ts";
import type { Kit } from "../../src/kits/types.ts";

type Listener = (event: { source: unknown; origin: string; data: unknown }) => void;

const fakeDocument = (withHead: boolean) => {
  const make = (tag: string) => {
    const children: any[] = [];
    const element: any = {
      tagName: tag,
      id: "",
      textContent: "",
      attributes: {} as Record<string, string>,
      get firstChild() {
        return children[0] ?? null;
      },
      insertBefore(child: any, before: any) {
        const at = before === null ? children.length : children.indexOf(before);
        children.splice(at, 0, child);
        return child;
      },
      appendChild(child: any) {
        children.push(child);
        return child;
      },
      setAttribute(name: string, value: string) {
        element.attributes[name] = value;
      },
      children,
    };
    return element;
  };
  const documentElement = make("html");
  const head = withHead ? make("head") : undefined;
  if (head) documentElement.appendChild(head);
  const all = () => {
    const found: any[] = [];
    const walk = (node: any) => {
      found.push(node);
      node.children.forEach(walk);
    };
    walk(documentElement);
    return found;
  };
  return {
    documentElement,
    head,
    createElement: (tag: string) => make(tag),
    getElementById: (id: string) => all().find((node) => node.id === id) ?? null,
  };
};

const stubWindow = (options: { withHead?: boolean; origin?: string; framed?: boolean; mode?: unknown; kit?: Kit | null; unframed?: unknown } = {}) => {
  const errors: unknown[][] = [];
  const messages: Listener[] = [];
  const events: string[] = [];
  const document = fakeDocument(options.withHead ?? true);
  const parent = { postMessage: () => {} };
  const win: any = {
    location: { origin: options.origin ?? "http://127.0.0.1:5001" },
    document,
    addEventListener: (type: string, listener: Listener) => {
      if (type === "message") messages.push(listener);
    },
    dispatchEvent: (event: { type: string }) => {
      events.push(event.type);
      return true;
    },
    Event: class {
      type: string;
      constructor(type: string) {
        this.type = type;
      }
    },
    console: { error: (...args: unknown[]) => errors.push(args) },
    __hfVariables: options.mode === undefined ? undefined : { unframedMode: options.mode },
  };
  win.parent = options.framed === false ? win : parent;
  if (options.unframed !== undefined) win.unframed = options.unframed;
  new Function("window", tokensScript(options.kit === undefined ? kit : options.kit))(win);
  const send = (data: unknown, from: { source?: unknown; origin?: string } = {}) => {
    for (const listener of messages) listener({ source: from.source ?? win.parent, origin: from.origin ?? "http://localhost:8787", data });
  };
  return { win, document, errors, events, send };
};

const kit: Kit = {
  format: 1,
  name: "Brand",
  modes: ["light", "dark"],
  tokens: [
    { path: "color/brand/primary", type: "color", values: { light: "#1a73e8", dark: "#8ab4f8" } },
    { path: "duration/fast", type: "duration", value: "200ms" },
    { path: "ease/out", type: "easing", value: "power2.out" },
    { path: "text/body", type: "textStyle", value: { fontFamily: "Inter", fontSize: "16px", fontWeight: 400, lineHeight: 1.5, letterSpacing: "0px" } },
  ],
};

describe("the tokens script", () => {
  it("starts with the generated-file comment", () => {
    expect(tokensScript(kit).split("\n")[0]).toMatch(/^\/\* unframed-tokens\.js: generated by Unframed from the project's kit and rewritten whenever the kit changes\. Do not edit it here/);
  });

  it("inserts the style as the first child of the head, with the kit's CSS", () => {
    const { document } = stubWindow();
    const style = document.head!.children[0];
    expect(style.tagName).toBe("style");
    expect(style.id).toBe("unframed-tokens");
    expect(style.textContent).toBe(kitCss(kit));
  });

  it("puts the style first in the document element when there is no head", () => {
    const { document } = stubWindow({ withHead: false });
    expect(document.documentElement.children[0].id).toBe("unframed-tokens");
  });

  it("chooses the mode from the render variables and sets data-theme to it", () => {
    expect(stubWindow({ mode: "dark" }).document.documentElement.attributes["data-theme"]).toBe("dark");
  });

  it("uses the default mode when no mode is given or the mode is not the kit's", () => {
    expect(stubWindow().document.documentElement.attributes["data-theme"]).toBe("light");
    expect(stubWindow({ mode: "neon" }).document.documentElement.attributes["data-theme"]).toBe("light");
  });

  it("defines unframed.token: the current mode's value, by path and by CSS name", () => {
    const { win } = stubWindow({ mode: "dark" });
    expect(win.unframed.token("color/brand/primary")).toBe("#8ab4f8");
    expect(win.unframed.token("--color-brand-primary")).toBe("#8ab4f8");
    expect(win.unframed.token("duration/fast")).toBeCloseTo(0.2);
    expect(win.unframed.token("ease/out")).toBe("power2.out");
    expect(win.unframed.token("text/body").fontSize).toBe("16px");
    expect(typeof win.unframed.token("ease/out")).toBe("string");
  });

  it("logs an error and returns undefined for a missing token", () => {
    const { win, errors } = stubWindow();
    expect(win.unframed.token("nope")).toBeUndefined();
    expect(errors).toEqual([["[unframed] no token nope"]]);
  });

  it("keeps the members an earlier script defined on window.unframed", () => {
    const { win } = stubWindow({ unframed: { dials: "kept" } });
    expect(win.unframed.dials).toBe("kept");
    expect(typeof win.unframed.token).toBe("function");
  });

  it("with no kit, defines unframed.token that is always undefined, and inserts no style", () => {
    const { win, document, errors } = stubWindow({ kit: null });
    expect(win.unframed.token("color/brand/primary")).toBeUndefined();
    expect(errors).toEqual([["[unframed] no token color/brand/primary"]]);
    expect(document.head!.children).toEqual([]);
  });
});

describe("the tokens script's messages", () => {
  it("sets the mode on a unframed:tokens:mode message from the parent, then dispatches unframed:tokens", () => {
    const { win, document, events, send } = stubWindow();
    send({ type: "unframed:tokens:mode", mode: "dark" });
    expect(document.documentElement.attributes["data-theme"]).toBe("dark");
    expect(events).toEqual(["unframed:tokens"]);
    expect(win.unframed.token("color/brand/primary")).toBe("#8ab4f8");
  });

  it("falls back to the default mode for a mode the kit does not have", () => {
    const { document, send } = stubWindow({ mode: "dark" });
    send({ type: "unframed:tokens:mode", mode: "neon" });
    expect(document.documentElement.attributes["data-theme"]).toBe("light");
  });

  it("replaces its kit and its style text in place on a unframed:tokens:set message", () => {
    const { document, events, win, send } = stubWindow();
    const style = document.head!.children[0];
    const next: Kit = { ...kit, tokens: [{ path: "color/brand/primary", type: "color", value: "#ff0000" }] };
    send({ type: "unframed:tokens:set", kit: next });
    expect(document.head!.children[0]).toBe(style);
    expect(style.textContent).toBe(kitCss(next));
    expect(events).toEqual(["unframed:tokens"]);
    expect(win.unframed.token("color/brand/primary")).toBe("#ff0000");
  });

  it("ignores a message that is not from its parent, or from another origin", () => {
    const { events, send, document } = stubWindow({ mode: "light" });
    send({ type: "unframed:tokens:mode", mode: "dark" }, { source: {} });
    send({ type: "unframed:tokens:mode", mode: "dark" }, { origin: "https://evil.example" });
    send({ type: "unframed:tokens:mode", mode: "dark" }, { origin: "http://localhost.evil.example:80" });
    expect(document.documentElement.attributes["data-theme"]).toBe("light");
    expect(events).toEqual([]);
    send({ type: "unframed:tokens:mode", mode: "dark" }, { origin: "http://[::1]:9000" });
    expect(document.documentElement.attributes["data-theme"]).toBe("dark");
  });

  it("ignores messages of other types", () => {
    const { events, send } = stubWindow();
    send({ type: "unframed:dials:set", values: {} });
    send(null);
    expect(events).toEqual([]);
  });
});

describe("a kit removed while the frame is open", () => {
  it("clears the style text it installed, and unframed.token answers undefined", () => {
    const { win, document, send } = stubWindow();
    const style = document.head!.children[0];
    expect(style.textContent).toBe(kitCss(kit));
    send({ type: "unframed:tokens:set", kit: null });
    expect(document.head!.children[0]).toBe(style);
    expect(style.textContent).toBe("");
    expect(win.unframed.token("color/brand/primary")).toBeUndefined();
  });
});

describe("the stamp", () => {
  it("is 8 hexadecimal characters, the same for the same kit, and changes with the kit", () => {
    expect(kitStamp(kit)).toMatch(/^[0-9a-f]{8}$/);
    expect(kitStamp(kit)).toBe(kitStamp(structuredClone(kit)));
    expect(kitStamp({ ...kit, tokens: [] })).not.toBe(kitStamp(kit));
  });

  it("ignores the library link, which is not in the script", () => {
    expect(kitStamp({ ...kit, from: { presetId: "p", revision: 3, base: { modes: [], tokens: [] } } })).toBe(kitStamp(kit));
  });
});
