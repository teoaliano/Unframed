/**
 * The tokens script (spec 19): `unframed-tokens.js`, the helper file that carries the kit into
 * every artifact. `tokensScript(kit)` builds its text; the installer embeds the kit runtime's
 * source text, so the tested definition and the shipped file are one. `kitStamp` names the
 * script's output, so a snapshot or a live frame can tell which kit it was made with.
 */
import { kitCore, type KitCore } from "./core.ts";
import { EASE_CSS } from "./easings.ts";
import type { Kit } from "./types.ts";
import { kitCss } from "./runtime.ts";

/** The window the installer runs against: a browser's, or a test's stub. */
export interface TokensWindow {
  readonly parent: unknown;
  readonly location: { readonly origin: string };
  readonly document: {
    readonly documentElement: { setAttribute(name: string, value: string): void; insertBefore?: unknown; firstChild?: unknown };
    readonly head: { insertBefore(node: unknown, before: unknown): unknown; firstChild: unknown } | null;
    createElement(tag: string): { id: string; textContent: string | null };
    getElementById(id: string): { id: string; textContent: string | null } | null;
  };
  addEventListener(type: "message", listener: (event: { source: unknown; origin: string; data: unknown }) => void): void;
  dispatchEvent(event: unknown): boolean;
  readonly Event: new (type: string) => unknown;
  __hfVariables?: { unframedMode?: unknown };
  unframed?: unknown;
  console: { error(...args: unknown[]): void };
}

/**
 * Installs the tokens: the style, the mode, `unframed.token` and the parent's messages. Self-
 * contained on purpose (it is shipped as source text): it refers to nothing outside its own
 * body except through `window`, `core` and `kit`.
 */
export function installTokens(win: TokensWindow, core: KitCore, initial: Kit | null): void {
  const LOOPBACK = /^http:\/\/(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/i;
  const STYLE_ID = "unframed-tokens";
  let kit: Kit | null = initial;
  let mode: string | undefined;

  const install = () => {
    if (kit === null) return;
    const doc = win.document;
    let style = doc.getElementById(STYLE_ID);
    if (style === null) {
      style = doc.createElement("style");
      style.id = STYLE_ID;
      const host = doc.head ?? (doc.documentElement as unknown as { insertBefore: (node: unknown, before: unknown) => unknown; firstChild: unknown });
      host.insertBefore(style, host.firstChild);
    }
    style.textContent = core.kitCss(kit);
  };

  const applyMode = (requested: unknown) => {
    if (kit === null) {
      mode = undefined;
      return;
    }
    mode = typeof requested === "string" && kit.modes.includes(requested) ? requested : kit.modes[0];
    win.document.documentElement.setAttribute("data-theme", mode!);
  };

  const token = (path: string): unknown => {
    const value = kit === null ? undefined : core.scriptValue(kit, path, mode);
    if (value === undefined) win.console.error("[unframed] no token " + path);
    return value;
  };

  const existing = typeof win.unframed === "object" && win.unframed !== null ? (win.unframed as Record<string, unknown>) : {};
  win.unframed = { ...existing, token };

  install();
  applyMode(win.__hfVariables?.unframedMode);

  win.addEventListener("message", (event) => {
    if (event.source !== win.parent) return;
    if (event.origin !== win.location.origin && !LOOPBACK.test(event.origin)) return;
    const data = event.data as { type?: unknown; mode?: unknown; kit?: unknown } | null;
    if (typeof data !== "object" || data === null) return;
    if (data.type === "unframed:tokens:mode") {
      applyMode(data.mode);
    } else if (data.type === "unframed:tokens:set") {
      const next = data.kit as { tokens?: unknown } | null;
      if (typeof next !== "object" || next === null || !Array.isArray(next.tokens)) return;
      kit = data.kit as Kit;
      applyMode(mode);
      install();
    } else {
      return;
    }
    win.dispatchEvent(new win.Event("unframed:tokens"));
  });
}

/** The kit as the script carries it: the record without its library link. */
const forScript = (kit: Kit | null): Partial<Kit> | null => (kit === null ? null : { format: kit.format, name: kit.name, modes: kit.modes, tokens: kit.tokens });

/** `unframed-tokens.js` for a kit, or for no kit. */
export const tokensScript = (kit: Kit | null): string =>
  [
    "/* unframed-tokens.js: generated by Unframed from the project's kit and rewritten whenever the kit changes. Do not edit it here: changes are lost. */",
    `(${installTokens.toString()})(window, (${kitCore.toString()})(${JSON.stringify(EASE_CSS)}), ${JSON.stringify(forScript(kit))});`,
    "",
  ].join("\n");

/**
 * An 8-character hash (FNV-1a) of a kit's CSS and modes: the stamp a snapshot, a live frame or a
 * render records. It hashes the data the script carries, not the script text, which depends on
 * how the source was built, so the stamp is the same in tests, the source run and the bundle.
 */
export const kitStamp = (kit: Kit | null): string => {
  const text = kit === null ? "no kit" : JSON.stringify({ css: kitCss(kit), modes: kit.modes });
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    hash ^= text.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, "0");
};
