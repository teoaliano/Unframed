import { BOARD_CAP, boardCellsRule } from "./board.ts";
import { COMPONENT_RUNTIME } from "./compile.ts";

export const COMPONENT_HELPER_FILE = "unframed-components.js";

export const COMPONENT_HELPER_TAG = `<script src="${COMPONENT_HELPER_FILE}"></script>`;

type Element = {
  textContent: string | null;
  innerHTML: string;
  style: { cssText: string };
  setAttribute(name: string, value: string): void;
  appendChild(child: Element): void;
};
type HelperWindow = {
  document: {
    readyState: string;
    body: Element;
    querySelector(selector: string): (Element & { textContent: string | null }) | null;
    createElement(tag: string): Element;
    addEventListener(type: string, listener: () => void): void;
  };
  location: { pathname: string };
  customElements: { get(tag: string): unknown };
};
const installComponentHelper = (
  win: HelperWindow,
  define: (decl: unknown, style: string, template: string, file: string) => void,
  boardRule: (declaration: { variants: Record<string, string[]> }, cap: number) => { cells: { values: Record<string, string>; label: string }[]; line?: string },
  cap: number,
) => {
  const doc = win.document;
  const note = (text: string) => {
    const line = doc.createElement("p");
    line.textContent = text;
    line.style.cssText = "font:13px system-ui, sans-serif;color:#6b6b6b;margin:0;padding:24px;background:#ffffff;";
    doc.body.appendChild(line);
  };
  const build = () => {
    const declScript = doc.querySelector('script[type="application/json"][data-uf-component]');
    const styleEl = doc.querySelector('style[data-uf-component-style]');
    const templateEl = doc.querySelector("[data-uf-template]");
    if (!declScript || !styleEl || !templateEl) return;
    let decl: { tag: string; variants: Record<string, string[]> };
    try {
      decl = JSON.parse(declScript.textContent || "{}") as { tag: string; variants: Record<string, string[]> };
    } catch {
      note("This component's declaration is not valid JSON, so it cannot be shown.");
      return;
    }
    const file = win.location.pathname.split("/").pop() || "";
    if (!win.customElements.get(decl.tag)) define(decl, styleEl.textContent || "", templateEl.innerHTML, file);
    const example = doc.querySelector("[data-uf-example]");
    const board = boardRule(decl, cap);
    const grid = doc.createElement("div");
    grid.style.cssText = "display:flex;flex-wrap:wrap;gap:24px;align-items:flex-start;padding:24px;background:#ffffff;";
    for (const cell of board.cells) {
      const item = doc.createElement("div");
      item.style.cssText = "display:flex;flex-direction:column;gap:8px;";
      const host = doc.createElement(decl.tag);
      host.setAttribute("data-uf-cell", "");
      for (const name of Object.keys(cell.values)) host.setAttribute(name, cell.values[name] ?? "");
      if (example) host.innerHTML = example.innerHTML;
      const label = doc.createElement("div");
      label.textContent = cell.label;
      label.style.cssText = "font:12px system-ui, sans-serif;color:#6b6b6b;max-width:240px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap;";
      label.setAttribute("title", cell.label);
      item.appendChild(host);
      item.appendChild(label);
      grid.appendChild(item);
    }
    if (board.line) {
      const line = doc.createElement("div");
      line.textContent = board.line;
      line.style.cssText = "font:12px system-ui, sans-serif;color:#6b6b6b;padding:0 24px 24px;";
      grid.appendChild(line);
    }
    doc.body.appendChild(grid);
  };
  if (doc.readyState === "loading") doc.addEventListener("DOMContentLoaded", build);
  else build();
};

export const componentHelperSource = (): string =>
  [
    "/* unframed-components.js: generated by Unframed and rewritten on every write. Do not edit it here: changes are lost. */",
    "(function () {",
    COMPONENT_RUNTIME.trim(),
    `(${installComponentHelper.toString()})(window, ufDefineComponent, ${boardCellsRule.toString()}, ${BOARD_CAP});`,
    "})();",
    "",
  ].join("\n");
