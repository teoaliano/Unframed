import { mkdir, readdir, readFile, rename, stat, utimes, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { scriptFolder, startAgentEngine } from "./agent.ts";
import { roomRecords } from "./agentCanvas.ts";
import { makeTempDir, startEngine, type TestEngine } from "./harness.ts";
import { connectTab } from "./syncClient.ts";

const DOCUMENT = "document:document";
const SCRIPT = "unframed-tokens.js";

const kit = (name = "Brand") => ({
  format: 1,
  name,
  modes: ["light", "dark"],
  tokens: [{ path: "color/brand/primary", type: "color", values: { light: "#1a73e8", dark: "#8ab4f8" } }],
});

const documentWith = (kitValue: unknown) => ({ id: DOCUMENT, typeName: "document", gridSize: 10, name: "", meta: kitValue === null ? {} : { unframed: { kit: kitValue } } });

/**
 * Whether a script file carries `kit`. The script's own text depends on how the domain
 * source was transformed (the engine's process and the test's differ), so the check reads the
 * kit the script embeds, not the whole text.
 */
const carries = (text: string | undefined, kitValue: { name: string } | null): boolean => {
  if (text === undefined || !text.startsWith("/* unframed-tokens.js: generated by Unframed")) return false;
  if (kitValue === null) return text.includes(", null);");
  const { format, name, modes, tokens } = kitValue as ReturnType<typeof kit>;
  return text.includes(JSON.stringify({ format, name, modes, tokens }) + ");");
};

/** Waits until the script file carries `kitValue`, so a write the engine makes after a commit can land. */
const settled = async (path: string, kitValue: { name: string } | null) => {
  const started = Date.now();
  for (;;) {
    const current = await readFile(path, "utf8").catch(() => undefined);
    if (carries(current, kitValue)) return;
    if (Date.now() - started > 10_000) throw new Error(`${path} never carried the expected kit`);
    await new Promise((resolve) => setTimeout(resolve, 25));
  }
};

describe("the tokens script in a project folder (spec 19, task 10)", () => {
  const engines: TestEngine[] = [];
  afterEach(async () => {
    for (const engine of engines.splice(0)) await engine.dispose();
  });

  const projectFolder = (engine: TestEngine) => join(engine.dataDir, "output", "board");

  it("writes the kit's script after a kit commit, and rewrites it after the next one", async () => {
    const engine = await startEngine({ env: { UNFRAMED_TEST_CANVAS: "1" } });
    engines.push(engine);
    await (await engine.rpc()).call("projects.create", { name: "board" });
    const rpc = await engine.rpc();
    const folder = projectFolder(engine);
    await rpc.call("testCanvas.apply", { project: "board", change: { put: [documentWith(kit())], remove: [] }, origin: { kind: "server", id: "kit:s1" } });
    await settled(join(folder, SCRIPT), kit());

    await rpc.call("testCanvas.apply", { project: "board", change: { put: [documentWith(kit("Second"))], remove: [] }, origin: { kind: "server", id: "kit:s5" } });
    await settled(join(folder, SCRIPT), kit("Second"));
  });

  it("writes the script for no kit when the kit is removed, and never rewrites a file already current", async () => {
    const engine = await startEngine({ env: { UNFRAMED_TEST_CANVAS: "1" } });
    engines.push(engine);
    await (await engine.rpc()).call("projects.create", { name: "board" });
    const rpc = await engine.rpc();
    const folder = projectFolder(engine);
    await rpc.call("testCanvas.apply", { project: "board", change: { put: [documentWith(null)], remove: [] }, origin: { kind: "server", id: "kit:s2" } });
    await settled(join(folder, SCRIPT), null);

    // A file that is already current is left alone: an old timestamp survives a commit that changes nothing.
    const past = new Date(2001, 0, 1);
    await utimes(join(folder, SCRIPT), past, past);
    await rpc.call("testCanvas.apply", { project: "board", change: { put: [documentWith(null)], remove: [] }, origin: { kind: "server", id: "kit:s3" } });
    expect((await stat(join(folder, SCRIPT))).mtimeMs).toBe(past.getTime());
  });

  it("rewrites a stale script when a room opens", async () => {
    const dataDir = await makeTempDir();
    const first = await startEngine({ dataDir, env: { UNFRAMED_TEST_CANVAS: "1" } });
    await (await first.rpc()).call("projects.create", { name: "board" });
    await (await first.rpc()).call("testCanvas.apply", { project: "board", change: { put: [documentWith(kit())], remove: [] }, origin: { kind: "server", id: "kit:s4" } });
    await first.dispose();

    const second = await startEngine({ dataDir, env: { UNFRAMED_TEST_CANVAS: "1" } });
    engines.push(second);
    await writeFile(join(projectFolder(second), SCRIPT), "/* stale */");
    const tab = await connectTab(second.port, "board");
    await tab.loaded;
    await settled(join(projectFolder(second), SCRIPT), kit());
    await tab.close();
  });

  it("ensures the script on an artifact write with no kit, and the page carries the tokens tag", async () => {
    const agent = await startAgentEngine({
      script: await scriptFolder({ artifacts: { when: "^go", turns: [{ text: "Done.", tools: [{ name: "page_write", input: { html: "<!doctype html><p>x</p>" } }] }] } }),
    });
    engines.push(agent.engine);
    const chatId = await agent.createChat();
    await agent.send(chatId, "go", {});
    await agent.settled(chatId, 1);
    expect(carries(await readFile(join(agent.folder, SCRIPT), "utf8"), null)).toBe(true);
    const created = (await roomRecords(agent)).find((record) => record.type === "page");
    expect(await readFile(join(agent.folder, created.props.file as string), "utf8")).toBe(
      `<script src="unframed-tokens.js"></script>\n<script src="unframed-dials.js"></script>\n<!doctype html><p data-hf-id="hf-8uol">x</p>`,
    );
  });
});

describe("the tokens script and a folder renamed while it is written", () => {
  it("leaves no temp file behind, in the renamed folder or beside it", async () => {
    const { ensureTokens } = await import("../src/kits/tokensFile.ts");
    const root = await makeTempDir();
    for (let round = 0; round < 40; round++) {
      const folder = join(root, `project-${round}`);
      await mkdir(folder);
      const write = ensureTokens(folder, kit() as Parameters<typeof ensureTokens>[1]);
      await new Promise((resolve) => setTimeout(resolve, round % 6));
      await rename(folder, join(root, `renamed-${round}`)).catch(() => undefined);
      await write.catch(() => undefined);
    }
    const names = await readdir(root, { recursive: true });
    expect(names.filter((name) => name.endsWith(".tmp"))).toEqual([]);
  }, 120_000);
});

describe("the tokens script and a project folder that is gone", () => {
  it("writes nothing and never recreates a folder that a rename or removal took away", async () => {
    const { ensureTokens } = await import("../src/kits/tokensFile.ts");
    const root = await makeTempDir();
    const gone = join(root, "renamed-away");
    await ensureTokens(gone, kit() as Parameters<typeof ensureTokens>[1]);
    await expect(stat(gone)).rejects.toThrow();
  });
});
